/// A country's Russian name, by its two-letter code in any case.
pub fn name(code: &str) -> Option<&'static str> {
    let code = code.to_ascii_lowercase();
    NAMES
        .binary_search_by(|(c, _)| c.cmp(&code.as_str()))
        .ok()
        .map(|i| NAMES[i].1)
}

/// The flag of a two-letter code: two regional indicator letters.
fn flag(code: &str) -> String {
    code.to_ascii_uppercase()
        .chars()
        .filter_map(|c| char::from_u32(0x1F1E6 + (c as u32 - 'A' as u32)))
        .collect()
}

/// A geoip entry as the phone shows it: a country by its flag and name,
/// `private` as the local networks, anything else — a company's addresses,
/// `telegram`, `cloudflare` — as it is written.
pub fn label(code: &str) -> String {
    if code.eq_ignore_ascii_case("private") {
        return "🏠 Локальные сети".to_owned();
    }
    match name(code) {
        Some(name) if code.len() == 2 && code.chars().all(|c| c.is_ascii_alphabetic()) => {
            format!("{} {name}", flag(code))
        }
        _ => format!("🌐 {code}"),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_country_reads_as_the_phone_shows_it() {
        assert_eq!(label("ru"), "🇷🇺 Россия");
        assert_eq!(label("DE"), "🇩🇪 Германия");
        assert_eq!(label("private"), "🏠 Локальные сети");
        assert_eq!(label("telegram"), "🌐 telegram");
        assert_eq!(label("zz"), "🌐 zz");
        // Sorted, or the search finds nothing past the first misplaced one.
        assert!(NAMES.windows(2).all(|w| w[0].0 < w[1].0));
    }
}
